#!/usr/bin/env bash
# Walkaway data operator: acts on data-series gaps the data watch (lib/data.sh) could not close by re-pulling.
#
#   data-operator.sh diagnose <series>   gaps marked need_operator (no re-pull path, or re-pull failed twice):
#                                        lost dates (source cannot re-pull) -> ESCALATED with the dates; else a
#                                        read-only diagnosis (headless claude) -> incident file + template-v2 fix plan
#                                        queued/launched in the owner repo (FIXING) or ONE question (ESCALATED)
#   data-operator.sh progress <series>   FIXING: follow the fix build; once it MERGED the gaps go back to OPEN with
#                                        the fix's date-range hook enabled, and the data watch re-pulls them
#
# Same contract as the job operator (lib/job-operator.sh, whose model call, plan queueing and repo lock it reuses):
# the model only reads; every action is done here in shell; one fix build per series per day; one builder per repo.
# Workspace: $WALKAWAY_HOME/data-fixes/<series>-<date>/handoff/{job-incident-<series>-<date>.md,
# build-plan-<feature>.md, evidence-<series>-<date>.json}.

set -uo pipefail

DOP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/data.sh
source "${DOP_DIR}/data.sh"
# job-operator.sh brings _jask (read-only claude -p + schema), _queue_or_launch (repo lock), _md_list, _et.
# shellcheck source=lib/job-operator.sh
source "${DOP_DIR}/job-operator.sh"
# shellcheck disable=SC2034  # read by operator.sh _other_active_build (skips this name)
FEATURE="data-operator"
# shellcheck disable=SC2034  # read by job-operator.sh _jask (the model's fixed system prompt)
WALKAWAY_JOB_OPERATOR_PROMPT="${WALKAWAY_DATA_OPERATOR_PROMPT:-${DOP_DIR}/../templates/data-operator-prompt.md}"

_do_ws() { echo "${WALKAWAY_HOME}/data-fixes/$1-$2/handoff"; }

# _period_word <series-json> -> day | week | month
_period_word() { jq -r '{"weekly": "week", "monthly": "month"}[.cadence // "daily"] // "day"' <<< "$1"; }

# _do_write_incident <ws> <series> <date> <decision-json> <evidence-json> <outcome-line> -> path
_do_write_incident() {
  local ws="$1" name="$2" d="$3" dec="$4" ev="$5" outcome="$6" f
  f="$ws/job-incident-${name}-${d}.md"
  {
    printf '# Data incident - %s - %s\n\n' "$name" "$d"
    printf 'Written by the walkaway data operator (read-only) at %s.\n\n' "$(_et)"
    printf '## Gaps\n'
    jq -r '.gaps[] | "- \(.period): \(.status) - rows \(.rows_now) / floor \(.floor) (rows when opened: \(.rows_before)); \(.reason); last try: \(.last_try // "none")"' <<< "$ev"
    printf '\n## Cause\n%s\n\n' "$(jq -r '.cause // "(no diagnosis: deterministic decision)"' <<< "$dec")"
    printf '## Evidence\n'; _md_list '.evidence' <<< "$dec"
    printf '\n## Decision\n%s\n' "$outcome"
    printf -- '- confidence: %s; protected_hit: %s; needs_live_action: %s\n' \
      "$(jq -r '.confidence // "-"' <<< "$dec")" "$(jq -r 'if .protected_hit == null then "-" else .protected_hit end' <<< "$dec")" \
      "$(jq -r 'if .needs_live_action == null then "-" else .needs_live_action end' <<< "$dec")"
    printf '\n## Fresh read-only counts (%s)\n```json\n%s\n```\n' "$(jq -r '.check.as_of' <<< "$ev")" \
      "$(jq '[.check.periods[] | {period, key, status, count}]' <<< "$ev" | head -c 6000)"
    printf '\n## Re-pull log (supervisor)\n```\n%s\n```\n' "$(jq -r '.repull_log | join("\n")' <<< "$ev" | tail -30)"
    printf '\nFull evidence: %s\n' "$ws/evidence-${name}-${d}.json"
  } > "$f"
  echo "$f"
}

# _do_render_plan <ws> <series-json> <date> <feature> <decision-json> <incident> <evidence-json> -> plan path
_do_render_plan() {
  local ws="$1" s="$2" d="$3" feature="$4" dec="$5" incident="$6" ev="$7" plan repo name
  name=$(jq -r .name <<< "$s"); repo=$(_expand_home "$(jq -r .owner_repo <<< "$s")")
  plan="$ws/build-plan-${feature}.md"
  {
    printf '# Walkaway Build Plan: %s\n\n' "$feature"
    printf 'Template v2 (2026-11-12, merge-gate standard). Auto-generated by the walkaway data operator for gaps in the\n%s series (incident: %s). The plan is the contract.\n\n' "$name" "$incident"
    printf '## Feature name\n`%s`\n\n## Branch name\n`feature/%s`\n\n## Repo\n`%s`\n\n' "$feature" "$feature" "$repo"
    printf '## Goal\n%s\n\n' "$(jq -r '.fix.goal // .fix.title' <<< "$dec")"
    printf '## Non-goals\n- Any other series or job, its schedule, or turning a pull off.\n- Dashboards or new monitoring.\n- Re-pulling live data: the walkaway supervisor does that after the merge through the hook below.\n\n'
    printf '## Evidence (do not re-derive)\n- Incident: %s (copied into handoff/ in Phase 0).\n' "$incident"
    printf -- '- Gaps: %s\n' "$(jq -r '[.gaps[] | "\(.period) \(.status) \(.rows_now)/\(.floor)"] | join(", ")' <<< "$ev")"
    printf -- '- Cause (data operator, read-only diagnosis): %s\n' "$(jq -r .cause <<< "$dec")"
    _md_list '.evidence' <<< "$dec"
    printf '\n## Decisions (who, when)\n- Jim 2026-11-15: every scheduled pull is watched for gaps; Claude launches fixes and re-pulls so there is no data loss. A re-pull of data is never protected; other protected actions unchanged (supervisor-v3-data).\n\n'
    printf '## Quality rules\n- Protocol "Merge-gate acceptance standard" applies in full.\n'
    printf -- '- "Fixed" means: the regression fixture built from this incident'"'"'s counts fails on the pre-fix commit and passes after, AND the date-range hook below exists exactly as written. Live confirmation is NOT the builder'"'"'s job: after the merge the walkaway supervisor calls the hook for the gap dates and confirms the rows landed (read-only count, floor %s).\n\n' "$(jq -r .floor <<< "$s")"
    printf '## Date-range re-pull hook (contract the supervisor calls after the merge, verbatim)\n%s\n' "$(jq -r '.fix_hook // "none"' <<< "$s")"
    jq -r '(.repull // [])[] | select(.requires_fix) | "- Supervisor call: `\(.command // .path)` with {from}/{to} = YYYY-MM-DD"' <<< "$s"
    printf '\n## Source of truth\n- Supabase `%s` (key `%s`%s), read-only counts per %s; floor %s (%s).\n- The incident counts archived in the incident file.\n\n' \
      "$(jq -r .table <<< "$s")" "$(jq -r .key.column <<< "$s")" "$(jq -r 'if (.filters // "") != "" then ", " + .filters else "" end' <<< "$s")" \
      "$(_period_word "$s")" "$(jq -r .floor <<< "$s")" "$(jq -r .floor_basis <<< "$s")"
    printf '## Acceptance criteria\n'
    jq -r '(.fix.acceptance_criteria // [])[] | "- [ ] \(.id) \(.text) (evidence: \(.evidence_file))"' <<< "$dec"
    printf -- '- [ ] ACH The date-range hook above exists exactly as written and pulls exactly the requested dates through the existing pull path (fixture test; evidence: handoff/%s-evidence/hook-test.txt).\n' "$feature"
    printf -- '- [ ] ACR Regression fixture from this incident: %s. Fails on the pre-fix commit, passes now (evidence: handoff/%s-evidence/regression.txt).\n' "$(jq -r '.fix.regression_fixture // "the incident counts"' <<< "$dec")" "$feature"
    printf -- '- [ ] ACG Gates: the repo typecheck, lint, full test suite vs baseline, build; CI green; Codex closed (evidence: handoff/%s-evidence/MANIFEST.md).\n\n' "$feature"
    printf '## Gate checklist (the operator executes this before merge)\n- Open handoff/%s-evidence/MANIFEST.md; every AC maps to a file.\n- Confirm the hook string in the code matches the contract above character for character.\n- Re-run the regression fixture result; confirm fail-on-pre-fix / pass-now.\n\n' "$feature"
    printf '## Escalate to Jim (never automatic)\n- Spend, credentials/logins/2FA, live writes to Audrey'"'"'s account or any publish/send, data deletion or overwrite, schedule changes, anything marked "Jim decides".\n\n'
    printf '## Expected files touched\nExpected: %s files plus the handoff copies (plan, incident, evidence, reports). Hard ceiling: %s.\n' "$(jq -r '(.fix.files_expected // []) | length' <<< "$dec")" "$(( $(jq -r '(.fix.files_expected // []) | length' <<< "$dec") + 4 ))"
    _md_list '.fix.files_expected' <<< "$dec"
    printf '\n## Phases\n'
    printf '### Phase 0: Prepare\n- Copy %s, %s and this plan into handoff/ and commit them on the branch. Confirm the cause against the code.\n' "$incident" "$ws/evidence-${name}-${d}.json"
    printf '### Phase 1: Fix\n'
    _md_list '.fix.what_to_build' <<< "$dec"
    printf '### Phase 5: Tests\n- The regression fixture above (must fail on the pre-fix commit) + the hook fixture test + the full suite.\n'
    printf '### Phase 6: Smoke (read-only)\n- Fixtures and read-only queries only. Never re-pull live data, never write or delete rows. Extension changes: note that the Mini needs a reload at chrome://extensions after the merge.\n'
    printf '### Phase 7: Codex review (cap 2), PR, CI, build report LAST (both files). Never merge.\n\n'
    printf '## Do NOT build\n- No changes to any other series or job, to schedules, or to existing rows.\n'
    _md_list '.fix.do_not_build' <<< "$dec"
    printf '\n## Stop rules (build-specific, in addition to WALKAWAY_BUILD_PROTOCOL.md)\n- Never write, overwrite or delete data rows, and never trigger a live pull during the build.\n'
    _md_list '.fix.stop_rules' <<< "$dec"
  } > "$plan"
  echo "$plan"
}

# do_diagnose <series>
do_diagnose() {
  local name="$1" cfg s d ws gaps ev dec decision protected live conf question forced="" incident hist pw
  cfg=$(data_config) || return 1
  s=$(data_get "$cfg" "$name"); d=$(data_today)
  gaps=$(jq -c '[.gaps | to_entries[] | select(.value.state == "OPEN" and .value.need_operator == true) | .key]' "$(_dstate_file "$name")")
  if [[ "$(jq 'length' <<< "$gaps")" == 0 ]]; then echo "no gaps need the operator"; return 0; fi
  ws=$(_do_ws "$name" "$d"); mkdir -p "$ws" "${WALKAWAY_HOME}/logs"
  local repo; repo=$(_expand_home "$(jq -r .owner_repo <<< "$s")")
  hist=$(jq -r '.historical // "unknown"' <<< "$s"); pw=$(_period_word "$s")

  # Evidence: the series entry, its state, the gaps with reasons, a fresh read-only count, the re-pull log.
  local chk rl
  chk=$(data_check "$cfg" "$name" "$(jq -c --argjson g "$gaps" '{skip: [], extra: $g}' <<< '{}')")
  rl=$(grep -F " $name: " "${WALKAWAY_HOME}/logs/data-repull.log" 2>/dev/null | tail -30 | jq -R . | jq -sc .)
  ev=$(jq -cn --argjson s "$s" --argjson st "$(dstate_json "$name")" --argjson c "$chk" --argjson g "$gaps" --argjson rl "${rl:-[]}" '
        {series: $s, state: $st, check: $c, repull_log: $rl,
         gaps: [$g[] as $p | $st.gaps[$p] + {period: $p, floor: $s.floor}]}')
  echo "$ev" | jq . > "$ws/evidence-${name}-${d}.json"
  local dates
  # shellcheck disable=SC2046  # one period per word
  dates=$(_dates_label $(jq -r '.[]' <<< "$gaps"))

  # Deterministic decisions first (no model).
  # 1. The source cannot re-pull a past period: those dates are lost unless rows arrive by themselves.
  if [[ "$hist" == "no" ]] && jq -e '[.gaps[] | .reason | startswith("no re-pull path")] | all' <<< "$ev" > /dev/null; then
    question="$name lost $dates ($(jq -r '[.gaps[] | "\(.rows_now)/\(.floor)"] | unique | join(", ")' <<< "$ev") rows): the source cannot re-pull a past $pw. Accept the loss, or fix the pull so it stops missing ${pw}s?"
    incident=$(_do_write_incident "$ws" "$name" "$d" '{}' "$ev" "ESCALATED (lost data): $question")
    dstate_update "$name" '.incident = $i | reduce $ps[] as $p (.; .gaps[$p].lost = true)' --arg i "$incident" --argjson ps "$gaps"
    # shellcheck disable=SC2046
    data_gap_transition "$name" ESCALATED "$question" $(jq -r '.[]' <<< "$gaps")
    return 0
  fi
  # 2. A fix for this series already merged and the re-pull through its hook still failed: no second fix loop.
  if jq -e '[.gaps[] | .post_fix == true] | any' <<< "$ev" > /dev/null; then
    question="$name $dates still $(jq -r '[.gaps[] | "\(.rows_now)/\(.floor)"] | unique | join(", ")' <<< "$ev") rows after fix $(dstate_get "$name" .fix_feature) merged and its hook re-pulled twice ($(jq -r '[.gaps[] | .last_try.label // "-"][0]' <<< "$ev" | cut -c1-80)). Was the extension reloaded / can you re-pull by hand?"
    incident=$(_do_write_incident "$ws" "$name" "$d" '{}' "$ev" "ESCALATED (post-fix re-pull failed): $question")
    dstate_update "$name" '.incident = $i' --arg i "$incident"
    # shellcheck disable=SC2046
    data_gap_transition "$name" ESCALATED "$question" $(jq -r '.[]' <<< "$gaps")
    return 0
  fi
  # 3. A fix build is already in flight for this series (registered and not MERGED, or still queued).
  local prev prev_state prev_plan
  prev=$(dstate_get "$name" .fix_feature); prev_plan=$(dstate_get "$name" .fix_plan); prev_state=""
  [[ -n "$prev" && "$(dstate_get "$name" .fix_merged)" != "true" ]] && prev_state=$(registry_get "$prev" .state)
  if [[ -n "$prev" && -z "$prev_state" && -n "$prev_plan" && "$(dstate_get "$name" .fix_merged)" != "true" ]] &&
     grep -qxF "$prev_plan" "$(queue_dir)/$(registry_repo_key "$repo").txt" 2>/dev/null; then
    prev_state="queued"
  fi
  if [[ -n "$prev_state" && "$prev_state" != "MERGED" ]]; then
    dstate_update "$name" 'reduce $ps[] as $p (.; .gaps[$p].need_operator = false)' --argjson ps "$gaps"
    # shellcheck disable=SC2046
    data_gap_transition "$name" FIXING "$dates join fix build $prev (still $prev_state)" $(jq -r '.[]' <<< "$gaps")
    return 0
  fi
  # 4. One auto-fix build per series per day.
  [[ "$(dstate_get "$name" .fix_date)" == "$d" ]] && forced="a fix build for $name already ran today ($prev)"

  if [[ -z "$forced" ]]; then
    local task
    task="MODE: DATA GAP DIAGNOSIS (read-only)

Series: $name ($(jq -r .title <<< "$s")); gaps: $dates ($pw periods under floor $(jq -r .floor <<< "$s"))
Why the supervisor could not close them: $(jq -r '[.gaps[] | .reason] | unique | join("; ")' <<< "$ev")
Owner repo (read its code; this is your working dir): $repo
Incident evidence JSON (series entry, gap state, fresh counts, re-pull log): $ws/evidence-${name}-${d}.json
Source can re-pull past periods: $hist
Date-range hook contract (the fix to build when no path exists; the supervisor calls it after the merge): $(jq -r '.fix_hook // "none"' <<< "$s")
Protocol: $WALKAWAY_PROTOCOL_PATH

Diagnose why these periods have no rows and whether the hook (plus any cause you find) fixes it. Decide fix (fill every fix field) or escalate (one question)."
    dec=$(_jask "$repo" "$ws" "$task")
  fi
  dec=${dec:-'{}'}
  decision=$(jq -r '.decision // ""' <<< "$dec")
  protected=$(jq -r 'if (.protected_hit | type) == "boolean" then .protected_hit else true end' <<< "$dec")
  live=$(jq -r 'if (.needs_live_action | type) == "boolean" then .needs_live_action else true end' <<< "$dec")
  conf=$(jq -r '.confidence // "low"' <<< "$dec"); question=$(jq -r '.question // ""' <<< "$dec")

  # Deterministic guards on top of the model.
  [[ -z "$forced" && -z "$decision" ]] && forced="diagnosis returned no decision"
  [[ -z "$forced" && "$protected" == "true" ]] && forced="protected action"
  [[ -z "$forced" && "$decision" == "fix" && "$live" == "true" ]] && forced="verifying the fix needs a live session"
  [[ -z "$forced" && "$decision" == "fix" && "$conf" != "high" ]] && forced="confidence $conf"
  [[ -z "$forced" && "$decision" == "fix" ]] && ! jq -e '(.fix.what_to_build // []) | length > 0' <<< "$dec" > /dev/null && forced="fix without what_to_build"

  if [[ "$decision" != "fix" || -n "$forced" ]]; then
    [[ -z "$question" ]] && question="$name $dates under floor ($(jq -r '[.gaps[] | .reason] | unique | join("; ")' <<< "$ev" | cut -c1-90)): ${forced:-cause unclear}. How should it be handled?"
    incident=$(_do_write_incident "$ws" "$name" "$d" "$dec" "$ev" "ESCALATED${forced:+ ($forced)}: $question")
    dstate_update "$name" '.incident = $i' --arg i "$incident"
    # shellcheck disable=SC2046
    data_gap_transition "$name" ESCALATED "$question" $(jq -r '.[]' <<< "$gaps")
    return 0
  fi

  local feature plan outcome
  feature="fix-data-${name}-${d//-/}"
  incident=$(_do_write_incident "$ws" "$name" "$d" "$dec" "$ev" "FIX BUILD $feature (template v2 plan: $ws/build-plan-${feature}.md)")
  plan=$(_do_render_plan "$ws" "$s" "$d" "$feature" "$dec" "$incident" "$ev")
  outcome=$(_queue_or_launch "$repo" "$plan" "$feature")
  dstate_update "$name" '.incident = $i | .fix_feature = $f | .fix_plan = $p | .fix_date = $d | .fix_merged = false
      | reduce $ps[] as $g (.; .gaps[$g].need_operator = false)' \
    --arg i "$incident" --arg f "$feature" --arg p "$plan" --arg d "$d" --argjson ps "$gaps"
  if [[ "$outcome" == LAUNCH-FAILED* ]]; then
    # shellcheck disable=SC2046
    data_gap_transition "$name" ESCALATED "${outcome#LAUNCH-FAILED }. Launch the fix for $name manually?" $(jq -r '.[]' <<< "$gaps")
    return 0
  fi
  # shellcheck disable=SC2046
  data_gap_transition "$name" FIXING "$dates: cause: $(jq -r '.cause | split(". ")[0] | .[0:150]' <<< "$dec"); $outcome" $(jq -r '.[]' <<< "$gaps")
}

# do_progress <series>: a FIXING series' fix build; MERGED -> its gaps go back to OPEN with the hook enabled.
do_progress() {
  local name="$1" feature fstate ps
  feature=$(dstate_get "$name" .fix_feature)
  [[ -n "$feature" && "$(dstate_get "$name" .fix_merged)" != "true" ]] || return 0
  if ! registry_exists "$feature"; then
    dstate_update "$name" '.last_action = $a' --arg a "fix build $feature queued (not launched yet)"; return 0
  fi
  fstate=$(registry_get "$feature" .state)
  if [[ "$fstate" != "MERGED" ]]; then
    dstate_update "$name" '.last_action = $a' --arg a "fix build $feature $fstate"; return 0
  fi
  ps=$(jq -c '[.gaps | to_entries[] | select(.value.state == "FIXING") | .key]' "$(_dstate_file "$name")")
  dstate_update "$name" '.fix_merged = true | .hook_merged = true
      | reduce $ps[] as $p (.; .gaps[$p] += {state: "OPEN", need_operator: false, post_fix: true, failed_tries: 0, tries_today: 0})
      | .last_action = $a' --argjson ps "$ps" \
    --arg a "fix $feature merged; re-pulling $(jq -r 'join(", ")' <<< "$ps") through its hook"
  _dlog "$name: fix $feature merged; $(jq -r 'length' <<< "$ps") gap(s) back to OPEN for the post-fix re-pull"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  mode="${1:-}"; series_arg="${2:-}"
  [[ -n "$mode" && -n "$series_arg" ]] || { echo "Usage: data-operator.sh <diagnose|progress> <series>" >&2; exit 1; }
  echo "[$(date '+%Y-%m-%d %H:%M:%S')] data-operator $mode $series_arg"
  case "$mode" in
    diagnose) do_diagnose "$series_arg" ;;
    progress) do_progress "$series_arg" ;;
    *) echo "data-operator: unknown mode $mode" >&2; exit 1 ;;
  esac
  [[ "$mode" == "diagnose" ]] && dstate_update "$series_arg" 'del(.operator_pid)'
fi
